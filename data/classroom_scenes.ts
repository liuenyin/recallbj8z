export function getClassroomScene(subject: SubjectKey, phase: Phase, week: number): ClassroomScene {
    const [early, late] = phase === Phase.SEMESTER_2 ? SCENES[subject].spring : SCENES[subject].fall;
    return week >= 11 && late ? late : early;
}
